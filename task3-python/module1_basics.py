# ============================================
# Упражнение 4. Доход по вкладу
# ============================================
print("\n--- Упражнение 4. Доход по вкладу ---")
deposit_amount = float(input("Введите сумму вклада (руб.): "))
interest_rate = float(input("Введите годовую ставку (%): "))
yearly_income = deposit_amount * (interest_rate / 100)
print(f"Доход за год: {yearly_income:.2f} руб.")

# ============================================
# Упражнение 5. Конвертер валюты
# ============================================
print("\n--- Упражнение 5. Конвертер валюты ---")
usd_rate = float(input("Введите курс доллара к рублю: "))
rub_amount = float(input("Введите сумму в рублях: "))
usd_amount = rub_amount / usd_rate
print(f"Сумма в долларах: {usd_amount:.2f} USD")