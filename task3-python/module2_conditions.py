print("\n--- Упражнение 1. Результат периода ---")
profit = float(input("Введите прибыль за месяц (руб.): "))
if profit > 0:
    print("Прибыль")
elif profit < 0:
    print("Убыток")
else:
    print("Безубыточность")

# ============================================
# Упражнение 2. Категория бизнеса
# ============================================
print("\n--- Упражнение 2. Категория бизнеса ---")
revenue = float(input("Введите годовую выручку (руб.): "))
if revenue < 1_000_000:
    print("Микробизнес")
elif revenue < 10_000_000:
    print("Малый бизнес")
elif revenue < 100_000_000:
    print("Средний бизнес")
else:
    print("Крупный бизнес")

# ============================================
# Упражнение 3. Расчёт НДФЛ
# ============================================
print("\n--- Упражнение 3. Расчёт НДФЛ ---")
salary = float(input("Введите зарплату (руб.): "))
if salary <= 50000:
    tax_rate = 13
else:
    tax_rate = 15
tax = salary * tax_rate / 100
net_salary = salary - tax
print(f"Налог: {tax:.2f} руб.")
print(f"Сумма на руки: {net_salary:.2f} руб.")

# ============================================
# Упражнение 4. Таблица умножения ставки
# ============================================
print("\n--- Упражнение 4. Таблица умножения ставки ---")
rate = float(input("Введите процентную ставку: "))
print(f"Таблица умножения ставки {rate}:")
for i in range(1, 13):
    print(f"{rate} × {i} = {rate * i:.2f}")

